// src/data/track-exercises.ts
// The STMS track & field layer.
//
// These entries are authored for STMS rather than imported. They cover the vocabulary a
// track coach actually uses — A-skips, flying 30s, 200m repeats, shot-put drills — which the
// public-domain gym dataset does not contain. Instructions are original coaching cues; see
// Docs/AgentsDocumentation/data-sources.md for the source and licence notes.
//
// An exercise is a movement or drill. The workout line owns the dose (sets, reps/distance,
// rest, target), so entries such as "200m Repeat" describe how to run the rep, not how many
// the athlete should do.

import type { ExerciseSeed, EventGroup } from '../types/exercise';

type TrackInput = Omit<
  ExerciseSeed,
  'source' | 'license' | 'createdBy' | 'contraindications' | 'tags' | 'secondaryMuscles'
> & {
  secondaryMuscles?: string[];
  contraindications?: string[];
  tags?: string[];
  imageUrl?: string | null;
};

function track(input: TrackInput): ExerciseSeed {
  const { secondaryMuscles = [], contraindications = [], tags: extraTags = [], ...rest } = input;
  const tags = [
    ...new Set(
      [
        rest.category,
        rest.phase,
        ...rest.eventGroups,
        ...rest.equipment,
        ...rest.primaryMuscles,
        ...secondaryMuscles,
        ...extraTags,
      ].map(value => value.toLowerCase())
    ),
  ];

  return {
    source: 'stms',
    license: 'STMS',
    createdBy: 'system',
    secondaryMuscles,
    contraindications,
    tags,
    ...rest,
  };
}

